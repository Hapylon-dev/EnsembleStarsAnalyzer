from PIL import Image
from PIL import ImageDraw


def create_canvas():

    img = Image.new(
        "RGB",
        (1366, 1024),
        (240, 238, 245)
    )

    draw = ImageDraw.Draw(img)

    # ----------------------
    # 緑ヘッダー
    # ----------------------

    draw.rounded_rectangle(
        (
            25,
            160,
            640,
            275
        ),
        radius=30,
        fill=(55, 230, 175)
    )

    # ----------------------
    # 白パネル
    # ----------------------

    draw.rounded_rectangle(
        (
            40,
            205,
            760,
            845
        ),
        radius=25,
        fill=(248, 248, 248)
    )

    # ----------------------
    # 区切り線
    # ----------------------

    draw.line(
        (55,390,735,390),
        fill=(180,205,205),
        width=2
    )

    draw.line(
        (55,550,735,550),
        fill=(180,205,205),
        width=2
    )

    # ----------------------
    # ジャケット枠
    # ----------------------

    draw.rectangle(
        (
            65,
            235,
            145,
            315
        ),
        outline=(215,215,215),
        width=2,
        fill=(255,255,255)
    )

    # ----------------------
    # グラフ背景
    # ----------------------

    draw.rectangle(
        (
            420,
            580,
            685,
            735
        ),
        fill=(238,244,242),
        outline=(190,210,210)
    )

    # ----------------------
    # グラフタイトル帯
    # ----------------------

    draw.rectangle(
        (
            420,
            550,
            685,
            580
        ),
        fill=(86,118,137)
    )

    # ----------------------
    # SLOWバー
    # ----------------------

    draw.rectangle(
        (
            420,
            745,
            552,
            770
        ),
        fill=(35,93,145)
    )

    # ----------------------
    # FASTバー
    # ----------------------

    draw.rectangle(
        (
            552,
            745,
            685,
            770
        ),
        fill=(255,88,45)
    )

    # ----------------------
    # 更新ボタン
    # ----------------------

    draw.ellipse(
        (
            700,
            170,
            745,
            215
        ),
        fill=(255,255,255),
        outline=(80,110,120),
        width=2
    )

    return img